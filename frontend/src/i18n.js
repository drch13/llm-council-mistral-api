export function createT(lang) {
  const dict = translations[lang] || translations.en;
  return (key, params) => {
    let s = dict[key] ?? translations.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
}
